export function localizedBlogPost(
  post: BlogPost,
  locale: "en" | "fa",
): BlogPost {
  if (locale === "en") return post;
  const entry = articles[post.slug];
  if (!entry) return post;
  const [title, excerpt] = entry;
  const [heading, first, second] = categoryGuidance[post.category];
  const insight = articleInsights[post.slug];
  return {
    ...post,
    title,
    excerpt,
    readTime: post.readTime.replace("min read", "دقیقه مطالعه"),
    content: `<p>${excerpt}</p><h2>${title}</h2><p>${insight}</p><h2>${heading}</h2><p>${first}</p><h2>پیش از تصمیم نهایی</h2><p>${second}</p>`,
  };
}

export function localizedBlogPosts(locale: "en" | "fa") {
  return blogPosts.map((post) => localizedBlogPost(post, locale));
}
